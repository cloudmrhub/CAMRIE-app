def run_gui():
    """Tkinter GUI for managing the CAMRIE Mode 2 worker."""
    try:
        import tkinter as tk
        from tkinter import ttk, scrolledtext
    except ImportError:
        print("tkinter not available. Use CLI mode or install python3-tk.")
        sys.exit(1)

    import threading
    import io
    import re

    root = tk.Tk()
    root.title("CAMRIE — Mode 2 Worker Manager")
    root.geometry("780x680")
    root.resizable(True, True)

    cfg = load_config()
    var_profile = tk.StringVar(value=cfg.get("profile", os.environ.get("AWS_PROFILE", "default")))
    var_region = tk.StringVar(value=cfg.get("region", DEFAULT_REGION))
    var_email = tk.StringVar(value=cfg.get("email", os.environ.get("CLOUDMR_EMAIL", "")))
    var_password = tk.StringVar(value=os.environ.get("CLOUDMR_PASSWORD", ""))
    var_alias = tk.StringVar(value=cfg.get("alias", "My CAMRIE Worker"))

    # ═══════════════════════════════════════════════════════════
    # Notebook (Tabs)
    # ═══════════════════════════════════════════════════════════
    notebook = ttk.Notebook(root)
    notebook.pack(fill="both", expand=True, padx=5, pady=5)

    # ═══════════════════════════════════════════════════════════
    # TAB 1: Worker Management
    # ═══════════════════════════════════════════════════════════
    worker_tab = ttk.Frame(notebook)
    notebook.add(worker_tab, text="  Worker  ")

    settings_frame = ttk.LabelFrame(worker_tab, text="Settings", padding=10)
    settings_frame.pack(fill="x", padx=10, pady=5)

    row = 0
    ttk.Label(settings_frame, text="AWS Profile:").grid(row=row, column=0, sticky="w", pady=2)
    profiles = get_aws_profiles()
    ttk.Combobox(settings_frame, textvariable=var_profile, values=profiles, width=43
                 ).grid(row=row, column=1, sticky="ew", pady=2, padx=(5, 0))
    row += 1

    for label, var, show in [
        ("AWS Region:", var_region, None),
        ("CloudMR Email:", var_email, None),
        ("CloudMR Password:", var_password, "*"),
        ("Worker Alias:", var_alias, None),
    ]:
        ttk.Label(settings_frame, text=label).grid(row=row, column=0, sticky="w", pady=2)
        entry = ttk.Entry(settings_frame, textvariable=var, width=45)
        if show:
            entry.config(show=show)
        entry.grid(row=row, column=1, sticky="ew", pady=2, padx=(5, 0))
        row += 1

    settings_frame.columnconfigure(1, weight=1)

    # Buttons
    btn_frame = ttk.Frame(worker_tab, padding=5)
    btn_frame.pack(fill="x", padx=10)

    # Log output
    log_frame = ttk.LabelFrame(worker_tab, text="Output", padding=5)
    log_frame.pack(fill="both", expand=True, padx=10, pady=5)

    log_widget = scrolledtext.ScrolledText(log_frame, height=14, font=("Courier", 10), state="disabled")
    log_widget.pack(fill="both", expand=True)

    def clear_log():
        log_widget.config(state="normal")
        log_widget.delete("1.0", "end")
        log_widget.config(state="disabled")

    def append_log(text):
        log_widget.config(state="normal")
        log_widget.insert("end", text + "\n")
        log_widget.see("end")
