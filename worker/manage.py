    def debug_lookup_pipeline():
        clear_debug()
        pipeline_id = var_pipeline_id.get().strip()
        email = var_email.get()
        password = var_password.get()

        if not pipeline_id:
            append_debug("Enter a pipeline ID first.")
            return

        def worker():
            try:
                if not email or not password:
                    print("Enter CloudMR credentials in the Worker tab.")
                    return
                auth = brain_login(email, password)
                token = auth.get("id_token") or auth.get("idToken")
                headers = {"Authorization": f"Bearer {token}"}

                print(f"Looking up pipeline: {pipeline_id}\n")
                resp = requests.get(f"{BRAIN_API_URL}/api/pipeline/{pipeline_id}", headers=headers)

                if resp.status_code != 200:
                    print(f"Pipeline not found (HTTP {resp.status_code})")
                    return

                data = resp.json()
                if isinstance(data, list):
                    data = data[0] if data else {}

                print(f"{'═'*60}")
                print(f"  Pipeline Details")
                print(f"{'═'*60}")
                print(f"  ID:      {pipeline_id}")
                print(f"  Status:  {data.get('status', 'unknown')}")
                print(f"  Alias:   {data.get('alias', 'N/A')}")
                print(f"  User:    {data.get('user_id', data.get('userId', 'N/A'))}")
                print(f"  Created: {data.get('created_at', data.get('createdAt', 'N/A'))}")

                # Show task details if available
                task = data.get("task", {})
                if task:
                    print(f"\n  Task:")
                    print(f"    Name: {task.get('name', '?')}")
                    print(f"    Type: {task.get('type', '?')}")
                    files = task.get("files", [])
                    print(f"    Files: {files}")
                    opts = task.get("options", {})
                    seqs = opts.get("sequences") or ([opts["sequence"]] if opts.get("sequence") else [])
                    if seqs:
                        print(f"    Sequences: {len(seqs)}")

                output = data.get("output") or data.get("results")
                if output:
                    print(f"\n  Output: {output}")

                    # Try to read the result/failure zip
                    if output.startswith("s3://"):
                        profile = var_profile.get() or "default"
                        try:
                            import tempfile, zipfile
                            parts = output.replace("s3://", "").split("/", 1)
                            bucket, key = parts[0], parts[1]
                            session = get_session(profile)
                            s3 = session.client("s3")
                            tmp = tempfile.NamedTemporaryFile(suffix=".zip", delete=False)
                            s3.download_file(bucket, key, tmp.name)
                            with zipfile.ZipFile(tmp.name, "r") as zf:
                                names = zf.namelist()
                                print(f"\n  Files in zip: {names}")
                                if "error.txt" in names:
                                    with zf.open("error.txt") as f:
                                        err = f.read().decode("utf-8", errors="replace")
                                    print(f"\n  Error:\n  {err.strip()[:500]}")
                            os.unlink(tmp.name)
                        except Exception as e:
                            print(f"\n  Could not read zip: {e}")

                print(f"\n{'═'*60}")

            except Exception as e:
                print(f"Error: {e}")

        def run():
            old_stdout = sys.stdout
            sys.stdout = buffer = io.StringIO()
            try:
                worker()
            finally:
                sys.stdout = old_stdout
                output = buffer.getvalue()
                clean = re.sub(r'\033\[[0-9;]*m', '', output)
                root.after(0, lambda: append_debug(clean))

        threading.Thread(target=run, daemon=True).start()

