def cmd_deploy(args):
    """Deploy the Mode 2 worker stack to AWS."""
    print(color("\n╔═══════════════════════════════════════════════╗", "blue"))
    print(color("║  CAMRIE Mode 2 — Deploy Worker                  ║", "blue"))
    print(color("╚═══════════════════════════════════════════════╝\n", "blue"))

    cfg = load_config()
    register = not getattr(args, "no_register", False)
    profile = args.profile or prompt("AWS CLI profile", cfg.get("profile", "default"))
    region = args.region or prompt("AWS region", cfg.get("region", DEFAULT_REGION))
    email = password = token = None
    if register:
        email = (args.email or os.environ.get("CLOUDMR_EMAIL")
                 or prompt("CloudMR email", cfg.get("email")))
        password = (args.password or os.environ.get("CLOUDMR_PASSWORD")
                    or prompt("CloudMR password", secret=True))
    api_key = args.api_key or cfg.get("api_key") or f"camrie-{uuid.uuid4().hex[:24]}"

    # Login to Brain first, so bad credentials fail before anything is created
    print(f"\n{color('[1/5]', 'bold')} Logging in to CloudMR Brain...")
    if register:
        auth = brain_login(email, password)
        token = auth.get("id_token") or auth.get("idToken")
        user_id = auth.get("user_id", "unknown")
        print(color(f"  Logged in as {email} (user: {user_id})", "green"))
    else:
        print(color("  Skipped (--no-register): stack only, no Brain registration", "yellow"))

    # Check AWS credentials
    print(f"\n{color('[2/5]', 'bold')} Checking AWS credentials...")
    session = get_session(profile, region)
    sts = session.client("sts")
    identity = sts.get_caller_identity()
    account_id = identity["Account"]
    print(color(f"  AWS Account: {account_id} ({profile})", "green"))

    # Detect networking
    print(f"\n{color('[3/5]', 'bold')} Detecting VPC and subnets...")
    ec2 = session.client("ec2")
    vpcs = ec2.describe_vpcs(Filters=[{"Name": "is-default", "Values": ["true"]}])["Vpcs"]
    if not vpcs:
        vpcs = ec2.describe_vpcs()["Vpcs"]
    vpc_id = vpcs[0]["VpcId"]

    subnets = ec2.describe_subnets(
        Filters=[{"Name": "vpc-id", "Values": [vpc_id]},
                 {"Name": "map-public-ip-on-launch", "Values": ["true"]}]
    )["Subnets"]
    if len(subnets) < 2:
        subnets = ec2.describe_subnets(
            Filters=[{"Name": "vpc-id", "Values": [vpc_id]}])["Subnets"]

    subnet1 = subnets[0]["SubnetId"]
    subnet2 = subnets[1]["SubnetId"] if len(subnets) > 1 else subnet1
    print(color(f"  VPC: {vpc_id}", "green"))
    print(color(f"  Subnets: {subnet1}, {subnet2}", "green"))

    # Deploy stack
    print(f"\n{color('[4/5]', 'bold')} Deploying CloudFormation stack...")
    print(f"  Stack: {STACK_NAME}")
    print(f"  This takes 2-3 minutes...\n")

    cf = session.client("cloudformation")
    with open(TEMPLATE_PATH) as f:
        template_body = f.read()

    params = [
        {"ParameterKey": "VpcId", "ParameterValue": vpc_id},
        {"ParameterKey": "SubnetId1", "ParameterValue": subnet1},
        {"ParameterKey": "SubnetId2", "ParameterValue": subnet2},
        {"ParameterKey": "WorkerApiKey", "ParameterValue": api_key},
        {"ParameterKey": "WorkerImageUri", "ParameterValue": ECR_IMAGE},
    ]
    caps = ["CAPABILITY_IAM", "CAPABILITY_AUTO_EXPAND"]

    existing, _ = get_stack_outputs(session)
    if existing in ("ROLLBACK_COMPLETE", "ROLLBACK_FAILED", "DELETE_FAILED"):
        # A stack in these states cannot be updated; it must be removed first.
        print(color(f"  Previous stack is {existing}; deleting it first...", "yellow"))
        empty_stack_buckets(session)
        cf.delete_stack(StackName=STACK_NAME)
        cf.get_waiter("stack_delete_complete").wait(
            StackName=STACK_NAME, WaiterConfig={"Delay": 10, "MaxAttempts": 60})
        existing = None

    wait_for = None
    if existing is None:
        cf.create_stack(StackName=STACK_NAME, TemplateBody=template_body,
                        Parameters=params, Capabilities=caps)
        wait_for = "stack_create_complete"
    else:
        try:
            cf.update_stack(StackName=STACK_NAME, TemplateBody=template_body,
                            Parameters=params, Capabilities=caps)
            wait_for = "stack_update_complete"
        except cf.exceptions.ClientError as e:
            if "No updates are to be performed" not in str(e):
                raise
            print(color("  Stack already up to date.", "green"))

    if wait_for:
        try:
            cf.get_waiter(wait_for).wait(
                StackName=STACK_NAME, WaiterConfig={"Delay": 10, "MaxAttempts": 60})
        except Exception as e:
            print(color(f"  Deploy failed: {e}", "red"))
            print_stack_failures(cf)
            sys.exit(1)

    status, outputs = get_stack_outputs(session)
    endpoint = outputs.get("WorkerEndpoint", "")
    print(color(f"  Stack deployed: {status}", "green"))
    print(color(f"  Endpoint: {endpoint}", "green"))

    if not register:
        print(color("\n  Stack is up. Brain registration skipped (--no-register).", "yellow"))
        save_config(profile=profile, region=region, endpoint=endpoint, api_key=api_key)
        return

    # Register with Brain
    print(f"\n{color('[5/5]', 'bold')} Registering with CloudMR Brain...")
    alias = args.alias or f"CAMRIE Worker ({profile})"
    payload = {
        "appName": APP_NAME,
        "mode": "mode_2",
        "provider": "self-hosted",
        "apiEndpoint": endpoint,
        "apiKey": api_key,
        "alias": alias,
        "awsAccountId": account_id,
        "region": region,
        "resultsBucket": "cloudmr-results-cloudmrhub-brain-us-east-1",
        "failedBucket": "cloudmr-failed-cloudmrhub-brain-us-east-1",
        "dataBucket": "cloudmr-data-cloudmrhub-brain-us-east-1",
    }
    resp = requests.post(
        f"{BRAIN_API_URL}/api/computing-unit/register",
        headers={"Authorization": f"Bearer {token}"},
        json=payload,
        timeout=60,
    )
    try:
        reg = resp.json()
    except ValueError:
        reg = {}
    cu_id = reg.get("computingUnitId")
    if resp.status_code >= 300 or not cu_id:
        # The stack is up; only registration failed. Say so rather than
        # printing a fake success - the web GUI won't list this worker.
        print(color(f"  Registration FAILED (HTTP {resp.status_code}): "
                    f"{str(reg or resp.text)[:300]}", "red"))
        print("  The stack is deployed. Re-run deploy to retry registration.")
        save_config(profile=profile, region=region, email=email,
                    alias=alias, endpoint=endpoint, api_key=api_key)
        sys.exit(1)
    print(color(f"  Registered: {alias} (ID: {cu_id})", "green"))

    print(color("\n  Done! Your CAMRIE Mode 2 worker is ready.", "green"))
    print(f"  Submit simulation jobs from the web app selecting your worker.")
    print(f"  Run 'python worker/manage.py status' to check health.")
    print(f"  Run 'python worker/manage.py teardown' to stop all costs.\n")

    save_config(profile=profile, region=region, email=email,
                alias=alias, endpoint=endpoint, api_key=api_key)


def cmd_status(args):
    """Check worker health and running tasks."""
    print(color("\n  CAMRIE Worker Status\n", "bold"))

    cfg = load_config()
    profile = args.profile or cfg.get("profile", "default")
    region = args.region or cfg.get("region", DEFAULT_REGION)
    session = get_session(profile, region)

    status, outputs = get_stack_outputs(session)
    if not status:
        print(color("  Stack not found. Run 'deploy' first.", "red"))
        return

    print(f"  Stack:    {STACK_NAME}")
    print(f"  Status:   {color(status, 'green' if 'COMPLETE' in status else 'yellow')}")

    endpoint = outputs.get("WorkerEndpoint", "")
    if endpoint:
        print(f"  Endpoint: {endpoint}")
        try:
            resp = requests.get(f"{endpoint}/health", timeout=10)
            health = resp.json()
            print(f"  Health:   {color('OK', 'green')}")
            print(f"  Type:     {health.get('type', 'unknown')}")
            print(f"  App:      {health.get('application', 'CAMRIE')}")
        except Exception as e:
            print(f"  Health:   {color(f'UNREACHABLE ({e})', 'red')}")

    cluster = outputs.get("ClusterName") or f"{STACK_NAME}-cluster"
    ecs = session.client("ecs")
    try:
        tasks = ecs.list_tasks(cluster=cluster)["taskArns"]
        print(f"\n  Running tasks: {len(tasks)}")
        for arn in tasks:
            detail = ecs.describe_tasks(cluster=cluster, tasks=[arn])["tasks"][0]
            started = detail.get("startedAt", "")
            lst = detail.get("lastStatus", "?")
            print(f"    {lst} — started {started}")
    except Exception:
        print(f"  Running tasks: 0")
    print()


def cmd_logs(args):
    """Tail recent computation logs."""
    cfg = load_config()
    profile = args.profile or cfg.get("profile", "default")
    region = args.region or cfg.get("region", DEFAULT_REGION)
    session = get_session(profile, region)

    log_group = f"/ecs/{STACK_NAME}"
    logs_client = session.client("logs")

    print(color(f"\n  Tailing logs: {log_group}\n", "bold"))
    print("  (Press Ctrl+C to stop)\n")

    start_time = int((datetime.utcnow() - timedelta(minutes=args.minutes)).timestamp() * 1000)
    seen = set()

    try:
        while True:
            try:
                resp = logs_client.filter_log_events(
                    logGroupName=log_group, startTime=start_time,
                    interleaved=True, limit=50)
            except logs_client.exceptions.ResourceNotFoundException:
                print(color("  No logs yet (no tasks have run).", "yellow"))
                break

            for event in resp.get("events", []):
                eid = event["eventId"]
                if eid in seen:
                    continue
                seen.add(eid)
                ts = datetime.fromtimestamp(event["timestamp"] / 1000).strftime("%H:%M:%S")
                msg = event["message"].strip()
                print(f"  [{ts}] {msg}")
                start_time = event["timestamp"] + 1

            if not args.follow:
                break
            time.sleep(2)
    except KeyboardInterrupt:
        print("\n  Stopped.")


def cmd_costs(args):
    """Show estimated costs from recent tasks."""
    cfg = load_config()
    profile = args.profile or cfg.get("profile", "default")
    region = args.region or cfg.get("region", DEFAULT_REGION)
    session = get_session(profile, region)

    print(color("\n  CAMRIE Cost Estimate (last 30 days)\n", "bold"))

    # Fargate pricing: $0.04048/vCPU/hr + $0.004445/GB/hr
    # CAMRIE config: 4 vCPU, 16 GB
    cost_per_sec = (0.04048 * 4 + 0.004445 * 16) / 3600

    cluster = f"{STACK_NAME}-cluster"
    ecs = session.client("ecs")

    try:
        stopped = ecs.list_tasks(cluster=cluster, desiredStatus="STOPPED")["taskArns"]
        total_seconds = 0

        if stopped:
            details = ecs.describe_tasks(cluster=cluster, tasks=stopped[:100])["tasks"]
            for t in details:
                started = t.get("startedAt")
                stopped_at = t.get("stoppedAt")
                if started and stopped_at:
                    total_seconds += (stopped_at - started).total_seconds()

        running = ecs.list_tasks(cluster=cluster, desiredStatus="RUNNING")["taskArns"]
        total_cost = total_seconds * cost_per_sec

        print(f"  Tasks completed:  {len(stopped)}")
        print(f"  Tasks running:    {len(running)}")
        print(f"  Total compute:    {total_seconds/60:.1f} minutes")
        print(f"  Estimated cost:   ${total_cost:.4f}")
        print(f"  (4 vCPU / 16 GB @ ${cost_per_sec*3600:.4f}/hr)")
        print(f"\n  Idle cost:        {color('$0.00', 'green')}")
        print()
    except Exception as e:
        print(f"  Could not retrieve task history: {e}")
        print(f"  Idle cost is $0.00 (no always-on resources).\n")


def cmd_teardown(args):
    """Delete the stack and deregister from Brain."""
    cfg = load_config()
    profile = args.profile or cfg.get("profile", "default")
    region = args.region or cfg.get("region", DEFAULT_REGION)
    session = get_session(profile, region)

    status, outputs = get_stack_outputs(session)
    if not status:
        print(color("  Stack not found. Nothing to tear down.", "yellow"))
        return

    print(color("\n  Teardown CAMRIE Mode 2 Worker\n", "bold"))
    print(f"  Stack:  {STACK_NAME}")
    print(f"  Status: {status}\n")

    if not args.yes:
        confirm = input(color("  Delete all resources? [y/N]: ", "yellow"))
        if confirm.lower() != "y":
            print("  Cancelled.")
            return

    # Deregister from Brain
    print("  Deregistering from CloudMR Brain...")
    email = args.email or os.environ.get("CLOUDMR_EMAIL") or cfg.get("email")
    password = args.password or os.environ.get("CLOUDMR_PASSWORD")
    if email and not password:
        password = prompt("CloudMR password (to deregister)", secret=True)

    if email and password:
        try:
            auth = brain_login(email, password)
            token = auth.get("id_token") or auth.get("idToken")
            endpoint = cfg.get("endpoint") or outputs.get("WorkerEndpoint", "")

            resp = requests.get(
                f"{BRAIN_API_URL}/api/computing-unit/list",
                headers={"Authorization": f"Bearer {token}"},
                params={"app_name": APP_NAME})
            units = resp.json().get("computingUnits", [])
            our_unit = next((u for u in units if u.get("apiEndpoint") == endpoint), None)

            if our_unit:
                cu_id = our_unit["computingUnitId"]
                requests.post(
                    f"{BRAIN_API_URL}/api/computing-unit/delete",
                    headers={"Authorization": f"Bearer {token}"},
                    json={"computingUnitId": cu_id})
                print(color(f"  Deregistered: {our_unit.get('alias')} ({cu_id})", "green"))
            else:
                print(color("  No matching unit found (already removed?).", "yellow"))
        except Exception as e:
            print(color(f"  Warning: deregister failed: {e}", "yellow"))
    else:
        print(color("  Skipping deregistration (no credentials).", "yellow"))

    # Delete stack (buckets must be empty or the delete fails)
    empty_stack_buckets(session)
    print("  Deleting CloudFormation stack...")
    cf = session.client("cloudformation")
    cf.delete_stack(StackName=STACK_NAME)
    waiter = cf.get_waiter("stack_delete_complete")
    waiter.wait(StackName=STACK_NAME, WaiterConfig={"Delay": 10, "MaxAttempts": 30})
    print(color("  Stack deleted. All costs stopped.", "green"))

    if CONFIG_PATH.exists():
        CONFIG_PATH.unlink()
        print(f"  Config removed: {CONFIG_PATH}")
    print()


