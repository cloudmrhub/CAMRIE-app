def color(text, c):
    colors = {"green": "\033[92m", "red": "\033[91m", "yellow": "\033[93m",
              "blue": "\033[94m", "bold": "\033[1m", "end": "\033[0m"}
    return f"{colors.get(c, '')}{text}{colors['end']}"


def get_session(profile=None, region=None):
    return boto3.Session(profile_name=profile, region_name=region or DEFAULT_REGION)


def get_stack_outputs(session, stack_name=STACK_NAME):
    cf = session.client("cloudformation")
    try:
        resp = cf.describe_stacks(StackName=stack_name)
        stack = resp["Stacks"][0]
        outputs = {o["OutputKey"]: o["OutputValue"] for o in stack.get("Outputs", [])}
        return stack["StackStatus"], outputs
    except Exception:
        return None, {}


def empty_stack_buckets(session, stack_name=STACK_NAME):
    """Empty the stack's S3 buckets. CloudFormation cannot delete a
    non-empty bucket, so teardown would otherwise fail with DELETE_FAILED."""
    _, outputs = get_stack_outputs(session, stack_name)
    s3 = session.resource("s3")
    for key in ("ResultsBucketName", "EventsBucketName"):
        name = outputs.get(key)
        if not name:
            continue
        try:
            bucket = s3.Bucket(name)
            bucket.object_versions.delete()
            bucket.objects.all().delete()
            print(f"  Emptied bucket {name}")
        except Exception as e:
            print(color(f"  Could not empty {name}: {e}", "yellow"))


def print_stack_failures(cf, stack_name=STACK_NAME):
    """Print the resources that failed, since the waiter error alone says nothing."""
    try:
        events = cf.describe_stack_events(StackName=stack_name)["StackEvents"]
        for ev in events[:40]:
            if ev["ResourceStatus"].endswith("FAILED"):
                print(color(f"    {ev['LogicalResourceId']}: "
                            f"{ev.get('ResourceStatusReason', '')}", "red"))
    except Exception:
        pass


def brain_login(email, password):
    resp = requests.post(f"{BRAIN_API_URL}/api/auth/login",
                         json={"email": email, "password": password})
    data = resp.json()
    token = data.get("id_token") or data.get("idToken") or data.get("access_token")
    if not token:
        print(color(f"Login failed: {data.get('message', 'Unknown error')}", "red"))
        sys.exit(1)
    return data


def prompt(text, default=None, secret=False):
    suffix = f" [{default}]" if default else ""
    if secret:
        import getpass
        val = getpass.getpass(f"{text}{suffix}: ")
    else:
        val = input(f"{text}{suffix}: ")
    return val.strip() or default


