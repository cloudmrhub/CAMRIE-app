def get_aws_profiles():
    """List available AWS CLI profiles."""
    profiles = set()
    for path in [Path.home() / ".aws" / "config", Path.home() / ".aws" / "credentials"]:
        if path.exists():
            with open(path) as f:
                for line in f:
                    line = line.strip()
                    if line.startswith("[profile "):
                        profiles.add(line[9:].rstrip("]"))
                    elif line.startswith("[") and not line.startswith("[default"):
                        profiles.add(line.strip("[]"))
    profiles.add("default")
    return sorted(profiles)


def load_config():
    """Load saved config from ~/.camrie/config.toml."""
    config = {}
    if CONFIG_PATH.exists():
        try:
            with open(CONFIG_PATH, encoding="utf-8", errors="replace") as f:
                for line in f:
                    line = line.strip()
                    if line and not line.startswith("#") and "=" in line:
                        key, val = line.split("=", 1)
                        config[key.strip()] = val.strip().strip('"').strip("'")
        except Exception:
            pass
    return config


def save_config(**kwargs):
    """Save config to ~/.camrie/config.toml."""
    CONFIG_DIR.mkdir(parents=True, exist_ok=True)
    lines = [
        "# CAMRIE Mode 2 — saved configuration",
        "# Auto-generated by manage.py deploy",
        f"# Location: {CONFIG_PATH}",
        "",
    ]
    for key, val in kwargs.items():
        if val:
            lines.append(f'{key} = "{val}"')
    lines.append("")
    CONFIG_PATH.write_text("\n".join(lines), encoding="utf-8")
    print(f"  Config saved to {CONFIG_PATH}")


